import type { Exercise, PlayerLesson, RichPart } from './types'

const SOURCE = 'https://docs.python.org/3/library/stdtypes.html#boolean-values'
const LABEL = 'Python docs'
const COLOR = '#1cb0f6'

const text = (value: string): RichPart => ({ text: value })
const code = (value: string): RichPart => ({ code: value })

function teach(partial: Omit<Exercise, 'type' | 'xp' | 'answer'> & { answer?: string }): Exercise {
  return {
    type: 'teach',
    xp: 0,
    answer: partial.answer ?? '',
    sourceUrl: SOURCE,
    sourceLabel: LABEL,
    ...partial,
  }
}

